// Browser stand-in for `xdev-export`, so the Agent context view runs without Tauri. The Rust crate is the truth.
import type { ExportFile, ExportStatus } from "./api";
import { fenceMarker, type Target } from "./doc/frontmatter";

export const EXPORT_MARKER = "<!-- Generated by xDev from the docs marked for agents. Edit those docs, not this file. -->";

export type ExportDoc = { source: string; title: string; targets: Target[]; body: string };

const CURSOR_HEAD = "---\ndescription: Project context generated by xDev\nalwaysApply: true\n---\n";

// First `# ` heading removed (the section has its own), the others one level deeper; code stays as is.
function sectionBody(body: string): string {
  const out: string[] = [];
  let dropped = false;
  let fence: string | null = null;
  for (const line of body.replace(/\r\n/g, "\n").split("\n")) {
    const marker = fenceMarker(line);
    if (marker !== null && (fence === null || fence === marker)) {
      fence = fence === null ? marker : null;
      out.push(line);
      continue;
    }
    if (fence !== null) {
      out.push(line);
      continue;
    }
    if (!dropped && line.startsWith("# ")) {
      dropped = true;
      continue;
    }
    out.push(/^#{1,5} /.test(line) ? `#${line}` : line);
  }
  while (out.length > 0 && out[0].trim() === "") out.shift();
  while (out.length > 0 && out.at(-1)!.trim() === "") out.pop();
  return out.join("\n");
}

function sections(docs: ExportDoc[], target: Target): string {
  return docs
    .filter((doc) => doc.targets.includes(target))
    .map((doc) => {
      const body = sectionBody(doc.body);
      return `\n\n## ${doc.title}\n_Source: \`${doc.source}\`_${body === "" ? "" : `\n\n${body}`}`;
    })
    .join("");
}

/** The generated files in their fixed order; docs are sorted by source first. */
export function renderExport(input: ExportDoc[]): { path: string; content: string }[] {
  const docs = [...input].sort((a, b) => (a.source < b.source ? -1 : a.source > b.source ? 1 : 0));
  const has = (target: Target) => docs.some((doc) => doc.targets.includes(target));
  const files: { path: string; content: string }[] = [];
  const agents = has("agents");
  const importLine = agents ? "\n\n@AGENTS.md" : "";
  if (agents) files.push({ path: "AGENTS.md", content: `${EXPORT_MARKER}\n# Agent guide${sections(docs, "agents")}\n` });
  if (agents || has("claude")) {
    files.push({ path: "CLAUDE.md", content: `${EXPORT_MARKER}\n# Claude Code guide${importLine}${sections(docs, "claude")}\n` });
  }
  if (agents || has("gemini")) {
    files.push({ path: "GEMINI.md", content: `${EXPORT_MARKER}\n# Gemini guide${importLine}${sections(docs, "gemini")}\n` });
  }
  if (has("cursor")) {
    files.push({
      path: ".cursor/rules/xdev.mdc",
      content: `${CURSOR_HEAD}${EXPORT_MARKER}\n# Cursor guide${sections(docs, "cursor")}\n`,
    });
  }
  return files;
}

// The `.mdc` frontmatter comes before the marker, so the marker may sit a few lines down.
function isGenerated(content: string): boolean {
  return content.split("\n").slice(0, 5).some((line) => line.replace(/\r$/, "") === EXPORT_MARKER);
}

export function exportStatus(old: string | null, next: string): ExportStatus {
  if (old === null) return "new";
  if (!isGenerated(old)) return "foreign";
  return old === next ? "unchanged" : "changed";
}

// Any stable content hash will do: the UI only hands it back to `exportWrite`.
async function hashOf(text: string): Promise<string> {
  const digest = await crypto.subtle.digest("SHA-256", new TextEncoder().encode(text));
  return [...new Uint8Array(digest)].map((b) => b.toString(16).padStart(2, "0")).join("");
}

export async function planExport(docs: ExportDoc[], onDisk: (path: string) => string | null): Promise<ExportFile[]> {
  return Promise.all(
    renderExport(docs).map(async ({ path, content }) => {
      const old = onDisk(path);
      return { path, status: exportStatus(old, content), old, new: content, hash: await hashOf(content) };
    }),
  );
}

export function estimateTokens(text: string): number {
  return Math.ceil([...text].length / 4);
}
