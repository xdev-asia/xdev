/// Same names and order as the vault's frontmatter targets. Kept separate so
/// this crate stays pure rendering with no dependency on the vault.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, serde::Serialize)]
#[cfg_attr(feature = "ts", derive(ts_rs::TS))]
#[serde(rename_all = "lowercase")]
pub enum Target {
    Agents,
    Claude,
    Gemini,
    Cursor,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ExportDoc {
    /// Relative to the export root, `/` separators.
    pub source: String,
    pub title: String,
    pub targets: Vec<Target>,
    /// Frontmatter already removed.
    pub body: String,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct OutFile {
    pub path: &'static str,
    pub content: String,
}

pub const MARKER: &str =
    "<!-- Generated by xDev from the docs marked for agents. Edit those docs, not this file. -->";

const CURSOR_HEAD: &str =
    "---\ndescription: Project context generated by xDev\nalwaysApply: true\n---\n";

pub fn render(docs: &[ExportDoc]) -> Vec<OutFile> {
    // Path order keeps the output identical across runs, so an unchanged
    // vault never shows a pending change.
    let mut docs: Vec<&ExportDoc> = docs.iter().collect();
    docs.sort_by(|a, b| a.source.cmp(&b.source));
    let has = |d: &ExportDoc, t: Target| d.targets.contains(&t);
    let sections = |keep: &dyn Fn(&ExportDoc) -> bool| -> String {
        docs.iter()
            .filter(|d| keep(d))
            .map(|d| section(d))
            .collect()
    };

    let agents = sections(&|d| has(d, Target::Agents));
    let with_agents = !agents.is_empty();
    let mut files = Vec::new();
    if with_agents {
        files.push(file("AGENTS.md", MARKER, "# Agent guide", &agents));
    }
    for (target, path, heading) in [
        (Target::Claude, "CLAUDE.md", "# Claude Code guide"),
        (Target::Gemini, "GEMINI.md", "# Gemini guide"),
    ] {
        // These files import AGENTS.md, so a doc already there would only
        // be repeated.
        let own = sections(&|d| has(d, target) && !has(d, Target::Agents));
        if with_agents || !own.is_empty() {
            let import = if with_agents { "\n\n@AGENTS.md" } else { "" };
            files.push(file(path, MARKER, heading, &format!("{import}{own}")));
        }
    }
    let cursor = sections(&|d| has(d, Target::Cursor));
    if !cursor.is_empty() {
        let head = format!("{CURSOR_HEAD}{MARKER}");
        files.push(file(
            ".cursor/rules/xdev.mdc",
            &head,
            "# Cursor guide",
            &cursor,
        ));
    }
    files
}

/// Characters, not bytes, so non-Latin docs are not overestimated.
pub fn estimate_tokens(text: &str) -> usize {
    text.chars().count().div_ceil(4)
}

fn file(path: &'static str, head: &str, heading: &str, rest: &str) -> OutFile {
    OutFile {
        path,
        content: format!("{head}\n{heading}{rest}\n"),
    }
}

fn section(doc: &ExportDoc) -> String {
    let mut out = format!("\n\n## {}\n_Source: `{}`_", doc.title, doc.source);
    let body = section_body(&doc.body);
    if !body.is_empty() {
        out.push_str("\n\n");
        out.push_str(&body);
    }
    out
}

/// The section heading replaces the doc's own title, and the doc's other
/// headings move one level down so they nest under it.
fn section_body(body: &str) -> String {
    let mut lines: Vec<String> = Vec::new();
    let mut fence: Option<(char, usize)> = None;
    let mut title_dropped = false;
    // `lines` also strips `\r`, so CRLF docs come out with `\n` endings.
    for line in body.lines() {
        if let Some((ch, len)) = fence {
            if closes_fence(line, ch, len) {
                fence = None;
            }
            lines.push(line.to_owned());
            continue;
        }
        if let Some(open) = opens_fence(line) {
            fence = Some(open);
            lines.push(line.to_owned());
            continue;
        }
        match heading_level(line) {
            1 if !title_dropped => title_dropped = true,
            1..=5 => lines.push(format!("#{line}")),
            _ => lines.push(line.to_owned()),
        }
    }
    let blank = |l: &&String| l.trim().is_empty();
    let start = lines.iter().position(|l| !blank(&l)).unwrap_or(lines.len());
    let end = lines
        .iter()
        .rposition(|l| !blank(&l))
        .map_or(start, |i| i + 1);
    lines[start..end].join("\n")
}

/// 0 when the line is not an ATX heading with a space after the `#`s.
fn heading_level(line: &str) -> usize {
    let level = line.bytes().take_while(|&b| b == b'#').count();
    if level > 0 && line.as_bytes().get(level) == Some(&b' ') {
        level
    } else {
        0
    }
}

fn fence_run(line: &str) -> Option<(char, usize, &str)> {
    // CommonMark allows up to three spaces before a fence.
    let indent = line.bytes().take_while(|&b| b == b' ').count();
    if indent > 3 {
        return None;
    }
    let rest = &line[indent..];
    let ch = rest.chars().next().filter(|c| matches!(c, '`' | '~'))?;
    let len = rest.chars().take_while(|&c| c == ch).count();
    (len >= 3).then(|| (ch, len, &rest[len..]))
}

fn opens_fence(line: &str) -> Option<(char, usize)> {
    fence_run(line).map(|(ch, len, _)| (ch, len))
}

fn closes_fence(line: &str, ch: char, len: usize) -> bool {
    matches!(fence_run(line), Some((c, n, rest)) if c == ch && n >= len && rest.trim().is_empty())
}
