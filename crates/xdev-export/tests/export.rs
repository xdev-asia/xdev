#[test]
fn plan_statuses() {
    let dir = TempDir::new().unwrap();
    let root = dir.path();
    fs::write(root.join("CLAUDE.md"), generated("same\n")).unwrap();
    fs::write(
        root.join("GEMINI.md"),
        format!("<!-- x -->\n{MARKER}\nold\n"),
    )
    .unwrap();

    let planned = plan(
        root,
        vec![
            out("AGENTS.md", &generated("a\n")),
            out("CLAUDE.md", &generated("same\n")),
            out("GEMINI.md", &generated("new\n")),
        ],
    )
    .unwrap();

    let statuses: Vec<_> = planned
        .iter()
        .map(|p| (p.path.as_str(), p.status))
        .collect();
    assert_eq!(
        statuses,
        [
            ("AGENTS.md", FileStatus::New),
            ("CLAUDE.md", FileStatus::Unchanged),
            ("GEMINI.md", FileStatus::Changed),
        ]
    );
    assert_eq!(planned[0].old, None);
    assert_eq!(
        planned[1].old.as_deref(),
        Some(generated("same\n").as_str())
    );
    assert_eq!(planned[2].new, generated("new\n"));
    assert_eq!(
        planned[0].hash,
        blake3::hash(generated("a\n").as_bytes())
            .to_hex()
            .to_string()
    );
}

#[test]
fn marker_after_line_five_is_foreign() {
    let dir = TempDir::new().unwrap();
    fs::write(
        dir.path().join("AGENTS.md"),
        format!("1\n2\n3\n4\n5\n{MARKER}\n"),
    )
    .unwrap();
    let planned = plan(dir.path(), vec![out("AGENTS.md", &generated("a\n"))]).unwrap();
    assert_eq!(planned[0].status, FileStatus::Foreign);
}

#[test]
fn non_utf8_file_is_foreign_with_lossy_old() {
    let dir = TempDir::new().unwrap();
    fs::write(dir.path().join("AGENTS.md"), b"\xff\xfeabc").unwrap();
    let planned = plan(dir.path(), vec![out("AGENTS.md", &generated("a\n"))]).unwrap();
    assert_eq!(planned[0].status, FileStatus::Foreign);
    assert_eq!(planned[0].old.as_deref(), Some("\u{fffd}\u{fffd}abc"));
    assert!(write(dir.path(), &planned).unwrap().is_empty());
    assert_eq!(
        fs::read(dir.path().join("AGENTS.md")).unwrap(),
        b"\xff\xfeabc"
    );
}

#[test]
fn foreign_file_is_never_written() {
    let dir = TempDir::new().unwrap();
    let root = dir.path();
    let hand_written = "# Our agent notes\r\n\r\nDo not touch.\r\n";
    fs::write(root.join("AGENTS.md"), hand_written).unwrap();

    let planned = plan(root, render(&golden_docs())).unwrap();
    assert_eq!(planned[0].path, "AGENTS.md");
    assert_eq!(planned[0].status, FileStatus::Foreign);
    assert_eq!(planned[0].old.as_deref(), Some(hand_written));

    let written = write(root, &planned).unwrap();
    assert_eq!(written, ["CLAUDE.md", "GEMINI.md"]);
    assert_eq!(
        fs::read(root.join("AGENTS.md")).unwrap(),
        hand_written.as_bytes()
    );
}

#[test]
fn write_creates_cursor_dir_and_returns_paths() {
    let dir = TempDir::new().unwrap();
    let root = dir.path();
    let docs = [
        doc("a.md", "A", &[Target::Agents], "Body"),
        doc("c.md", "C", &[Target::Cursor], "Rule"),
    ];
    let files = render(&docs);
    let planned = plan(root, files).unwrap();

    let written = write(root, &planned).unwrap();
    assert_eq!(
        written,
        [
            "AGENTS.md",
            "CLAUDE.md",
            "GEMINI.md",
            ".cursor/rules/xdev.mdc"
        ]
    );
    for p in &planned {
        assert_eq!(read(root, &p.path), p.new);
    }
    let leftovers: Vec<_> = fs::read_dir(root.join(".cursor/rules"))
        .unwrap()
        .map(|e| e.unwrap().file_name())
        .collect();
    assert_eq!(leftovers, ["xdev.mdc"]);

    let again = plan(root, render(&docs)).unwrap();
    assert!(again.iter().all(|p| p.status == FileStatus::Unchanged));
    assert!(write(root, &again).unwrap().is_empty());
}

#[test]
fn write_refuses_when_disk_changed() {
    let dir = TempDir::new().unwrap();
    let root = dir.path();
    fs::write(root.join("GEMINI.md"), generated("old\n")).unwrap();

    let planned = plan(root, render(&golden_docs())).unwrap();
    fs::write(root.join("GEMINI.md"), generated("edited\n")).unwrap();

    let err = write(root, &planned).unwrap_err();
    assert!(matches!(err, ExportError::Stale));
    assert_eq!(err.code(), "stale");
    assert!(!root.join("AGENTS.md").exists());
    assert!(!root.join("CLAUDE.md").exists());
    assert_eq!(read(root, "GEMINI.md"), generated("edited\n"));
}

#[test]
fn write_refuses_when_new_file_appeared() {
    let dir = TempDir::new().unwrap();
    let root = dir.path();
    let planned = plan(root, render(&golden_docs())).unwrap();
    fs::write(root.join("CLAUDE.md"), "mine").unwrap();

    assert!(matches!(write(root, &planned), Err(ExportError::Stale)));
    assert!(!root.join("AGENTS.md").exists());
    assert_eq!(read(root, "CLAUDE.md"), "mine");
}

#[test]
fn target_order_is_file_order() {
    let mut targets = vec![
        Target::Cursor,
        Target::Gemini,
        Target::Claude,
        Target::Agents,
    ];
    targets.sort();
    assert_eq!(
        targets,
        [
            Target::Agents,
            Target::Claude,
            Target::Gemini,
            Target::Cursor
        ]
    );
}

