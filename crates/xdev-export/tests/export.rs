use std::fs;
use std::path::Path;

use tempfile::TempDir;
use xdev_export::{
    ExportDoc, ExportError, FileStatus, MARKER, OutFile, Target, estimate_tokens, plan, render,
    write,
};

fn doc(source: &str, title: &str, targets: &[Target], body: &str) -> ExportDoc {
    ExportDoc {
        source: source.to_owned(),
        title: title.to_owned(),
        targets: targets.to_vec(),
        body: body.to_owned(),
    }
}

fn golden_docs() -> Vec<ExportDoc> {
    vec![
        doc(
            "docs/a.md",
            "A",
            &[Target::Agents],
            "# A\n\nIntro\n\n## Part\n\n```\n# not a heading\n```\n",
        ),
        doc("docs/b.md", "B", &[Target::Claude], "Claude only"),
    ]
}

fn paths(files: &[OutFile]) -> Vec<&'static str> {
    files.iter().map(|f| f.path).collect()
}

fn content<'a>(files: &'a [OutFile], path: &str) -> &'a str {
    &files.iter().find(|f| f.path == path).unwrap().content
}

fn out(path: &'static str, content: &str) -> OutFile {
    OutFile {
        path,
        content: content.to_owned(),
    }
}

fn generated(body: &str) -> String {
    format!("{MARKER}\n{body}")
}

fn read(root: &Path, rel: &str) -> String {
    fs::read_to_string(root.join(rel)).unwrap()
}

#[test]
fn render_golden() {
    let files = render(&golden_docs());
    assert_eq!(paths(&files), ["AGENTS.md", "CLAUDE.md", "GEMINI.md"]);
    assert_eq!(
        content(&files, "AGENTS.md"),
        format!(
            "{MARKER}\n# Agent guide\n\n## A\n_Source: `docs/a.md`_\n\nIntro\n\n### Part\n\n```\n# not a heading\n```\n"
        )
    );
    assert_eq!(
        content(&files, "CLAUDE.md"),
        format!(
            "{MARKER}\n# Claude Code guide\n\n@AGENTS.md\n\n## B\n_Source: `docs/b.md`_\n\nClaude only\n"
        )
    );
    assert_eq!(
        content(&files, "GEMINI.md"),
        format!("{MARKER}\n# Gemini guide\n\n@AGENTS.md\n")
    );
}

#[test]
